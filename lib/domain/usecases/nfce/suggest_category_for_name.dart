  Future<String?> call(String name) async {
    final normalized = StringNormalizer.normalize(name);
    final categoryName = _findByKeywords(normalized);
    final categories = await _categoryRepository.getAll();
    final fallback = _findByName(categories, 'Outros');
    if (categoryName == null) return fallback?.id;
    final match = _findByName(categories, categoryName);
    return (match ?? fallback)?.id;
  }

  String? _findByKeywords(String normalized) {
    for (final entry in _keywordMap.entries) {
      for (final keyword in entry.value) {
        if (normalized.contains(keyword)) return entry.key;
      }
    }
    return null;
  }

  Category? _findByName(List<Category> categories, String name) {
    final matches = categories.where((c) => c.name == name);
    return matches.isEmpty ? null : matches.first;
  }
}
